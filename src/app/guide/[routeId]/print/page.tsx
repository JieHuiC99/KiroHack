import type { Metadata } from "next";
import { headers } from "next/headers";
import Image from "next/image";
import { notFound } from "next/navigation";
import QRCode from "qrcode";
import { Suspense } from "react";
import { checkpointUrl, getLandmarkRoute } from "@/lib/landmark-routes";

export const metadata: Metadata = { title: "SafeWay — QR codes to print" };

/** The address people reach this app at, so the printed codes point back to it. */
async function siteOrigin() {
  const incoming = await headers();
  const host = incoming.get("x-forwarded-host") ?? incoming.get("host") ?? "localhost:3000";
  const protocol = incoming.get("x-forwarded-proto") ?? (host.startsWith("localhost") ? "http" : "https");
  return `${protocol}://${host}`;
}

async function Sheet({ params }: { params: PageProps<"/guide/[routeId]/print">["params"] }) {
  const { routeId } = await params;
  const route = getLandmarkRoute(routeId);
  if (!route) notFound();
  const origin = await siteOrigin();
  const codes = await Promise.all(
    route.checkpoints.map(async (checkpoint) => {
      const url = checkpointUrl(origin, route, checkpoint);
      return { checkpoint, url, svg: await QRCode.toString(url, { type: "svg", margin: 2, errorCorrectionLevel: "M" }) };
    }),
  );

  return (
    <main className="mx-auto flex w-full max-w-5xl flex-col gap-5 p-4 text-lg sm:p-6">
      <header className="print:hidden">
        <h1 className="text-3xl font-bold">QR codes: {route.name}</h1>
        <p>
          Print this page and stick each code on the wall beside its landmark, at chest height. The codes point to <strong>{origin}</strong>: print them from the
          address people will really use, not from localhost.
        </p>
      </header>
      <ol className="grid gap-4 sm:grid-cols-2 print:grid-cols-2">
        {codes.map(({ checkpoint, url, svg }, index) => (
          <li key={checkpoint.id} className="flex break-inside-avoid flex-col gap-2 rounded-xl border-2 border-black p-4">
            <p className="text-xl font-bold">
              {index + 1}. {checkpoint.title} <span className="font-normal">· {checkpoint.level}</span>
            </p>
            <div className="flex items-start gap-3">
              {/* Markup generated by the qrcode library from our own address: nothing user-supplied in it. */}
              <div className="size-44 shrink-0" dangerouslySetInnerHTML={{ __html: svg }} />
              <Image src={checkpoint.image} alt="" width={640} height={850} unoptimized loading="eager" className="h-44 w-32 rounded-lg object-cover" />
            </div>
            <p className="text-base">Stick beside: {checkpoint.look}</p>
            <p className="text-xs break-all text-neutral-600">{url}</p>
          </li>
        ))}
      </ol>
    </main>
  );
}

export default function PrintPage({ params }: PageProps<"/guide/[routeId]/print">) {
  return (
    <Suspense>
      <Sheet params={params} />
    </Suspense>
  );
}
